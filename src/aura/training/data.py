def build_preference_dataset(
    *,
    psychology_limit: int | None = 3000,
    seed: int = 3407,
    eval_fraction: float = 0.05,
) -> tuple[Any, Any | None]:
    """Load both sources and return ``(train, eval)`` HuggingFace datasets."""
    from datasets import Dataset, load_dataset

    stats = BuildStats()
    pairs: list[PreferencePair] = []

    log.info("loading %s", PSYCHOLOGY_DATASET)
    split = f"train[:{psychology_limit}]" if psychology_limit else "train"
    psychology = load_dataset(PSYCHOLOGY_DATASET, split=split)
    pairs.extend(build_psychology_pairs(psychology, stats, limit=psychology_limit))
    log.info("psychology pairs: %d", len(pairs))

    log.info("loading %s", COACHING_DATASET)
    try:
        coaching = load_dataset(COACHING_DATASET, split="train")
        before = len(pairs)
        pairs.extend(build_coaching_pairs(coaching, stats, seed=seed))
        log.info("coaching pairs: %d", len(pairs) - before)
    except Exception as exc:  # the coaching set is optional, not required
        log.warning("skipping the coaching dataset: %s", exc)

    pairs = deduplicate(pairs)
    random.Random(seed).shuffle(pairs)
    log.info("dataset built — %s, %d unique pairs", stats.summary(), len(pairs))

    if not pairs:
        raise RuntimeError("no usable preference pairs were produced")

    rows = [pair.as_dict() for pair in pairs]
    if eval_fraction <= 0 or len(rows) < 40:
        return Dataset.from_list(rows), None

    cut = max(1, int(len(rows) * eval_fraction))
    return Dataset.from_list(rows[cut:]), Dataset.from_list(rows[:cut])


def to_sft_dataset(preference_dataset: Any, tokenizer: Any) -> Any:
    """Project preference pairs to SFT text by keeping only ``chosen``."""
    from datasets import Dataset

    rows = []
    for row in preference_dataset:
        conversation = [
            {"role": "user", "content": row["prompt"]},
            {"role": "assistant", "content": row["chosen"]},
        ]
        text = tokenizer.apply_chat_template(
            conversation, tokenize=False, add_generation_prompt=False
        )
        rows.append({"text": text.removeprefix("<bos>")})
    return Dataset.from_list(rows)
