def build_psychology_pairs(
    dataset: Iterable[dict[str, Any]], stats: BuildStats, *, limit: int | None = None
) -> Iterator[PreferencePair]:
    """``question`` + preferred (``response_j``) vs dispreferred (``response_k``)."""
    for index, row in enumerate(dataset):
        if limit is not None and index >= limit:
            break
        prompt = normalise(row.get("question"))
        chosen = normalise(row.get("response_j"))
        rejected = normalise(row.get("response_k"))
        if not (prompt and chosen and rejected):
            stats.seen += 1
            stats.drop("missing_field")
            continue
        # Hand the turn back, so preference also covers "ends with an opening".
        invitation = COACHING_INVITATIONS[index % len(COACHING_INVITATIONS)]
        pair = PreferencePair(prompt, f"{chosen}\n\n{invitation}", rejected, "psychology")
        if validate(pair, stats):
            yield pair


def build_coaching_pairs(
    dataset: Iterable[dict[str, Any]], stats: BuildStats, *, seed: int = 3407
) -> Iterator[PreferencePair]:
    """Real coach turns as ``chosen``; a generic directive reply as ``rejected``.

    Only assistant turns that ask a question are taken, because the question is
    the coaching move we are trying to reinforce.
    """
    rng = random.Random(seed)
    for row in dataset:
        messages = row.get("messages") or []
        for current, following in itertools.pairwise(messages):
            if current.get("role") != "user" or following.get("role") != "assistant":
                continue
            client = normalise(current.get("content"))
            coach = normalise(following.get("content"))
            if "?" not in coach:
                stats.seen += 1
                stats.drop("no_question")
                continue
            pair = PreferencePair(client, coach, rng.choice(DIRECTIVE_REJECTIONS), "coaching")
            if validate(pair, stats):
                yield pair


